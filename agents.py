"""Агенти. Кожен агент = системний промпт + виклик моделі. Нічого більше."""
import json
import re

import anthropic

import config

_client = None


def set_api_key(key: str):
    """Інтерфейс передає ключ сюди; без виклику береться змінна ANTHROPIC_API_KEY."""
    global _client
    _client = anthropic.Anthropic(api_key=key)


def _get_client():
    global _client
    if _client is None:
        _client = anthropic.Anthropic()
    return _client


def ask(system: str, user: str, max_tokens: int = 4000) -> str:
    resp = _get_client().messages.create(
        model=config.MODEL,
        max_tokens=max_tokens,
        system=system,
        messages=[{"role": "user", "content": user}],
    )
    return resp.content[0].text


def ask_json(system: str, user: str) -> dict:
    text = ask(system + "\nВідповідай ЛИШЕ валідним JSON, без пояснень і без ```.", user)
    match = re.search(r"\{.*\}", text, re.S)
    return json.loads(match.group(0))


